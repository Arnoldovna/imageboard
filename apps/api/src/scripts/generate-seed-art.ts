/**
 * `pnpm --filter @app/api seed:generate-art`: draws the sixteen seed pictures (ADR 0014, DATA-MODEL §6.2). Every
 * piece in `seed-art/pieces.ts` is SVG composed in code; sharp (librsvg) renders it and writes
 * `seed/images/<slug>.jpg` (long edge ≤ 1600 px, JPEG q82, no metadata), then `CREDITS.md` is regenerated.
 *
 * The output is committed, so `db:seed` and the Pages demo work offline and nothing points at a third party (B-44).
 * Nothing is downloaded and nothing is random between runs: each piece has its own seed, so a re-run with the same
 * sharp/libvips version writes the same files.
 */
import { rename, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import sharp from 'sharp';

import { renderSvg, SEED_ARTWORKS, type SeedArtwork } from './seed-art/pieces.js';
import { joinSeed, readManifest, SEED_IMAGES, SEED_IMAGES_DIR } from './seed-content.js';
import { cliArgs, runCli } from './script-cli.js';

/** Long edge of a stored seed picture; the upload pipeline keeps it (IMAGE_MAX_EDGE is larger). */
export const SEED_MAX_EDGE = 1600;
const JPEG_QUALITY = 82;

/** sharp writes no EXIF/XMP/ICC unless asked to (`withMetadata`), so the JPEG carries pixels only. */
export async function renderJpeg(artwork: SeedArtwork): Promise<Buffer> {
  if (Math.max(artwork.width, artwork.height) > SEED_MAX_EDGE) {
    throw new Error(
      `${artwork.slug}: ${String(artwork.width)}×${String(artwork.height)} exceeds ${String(SEED_MAX_EDGE)} px`,
    );
  }
  return sharp(Buffer.from(renderSvg(artwork)))
    .jpeg({ quality: JPEG_QUALITY, mozjpeg: true })
    .toBuffer();
}

/** Markdown that Prettier leaves as it is (no tables to re-align), so a re-run never fails `format:check`. */
export function renderCredits(): string {
  const titles = new Map(SEED_IMAGES.map((image) => [image.slug, image.title]));
  const list = SEED_ARTWORKS.map(
    (artwork) =>
      `- \`${artwork.slug}.jpg\`: "${titles.get(artwork.slug) ?? artwork.slug}", ${String(artwork.width)}×${String(artwork.height)} px`,
  );
  return [
    '# Seed image credits',
    '',
    'The demo content of `pnpm db:seed` and of the live demo uses these sixteen pictures. They are original',
    'illustrations inspired by Art Nouveau and Art Deco in general, drawn in code by',
    '`apps/api/src/scripts/generate-seed-art.ts` (shapes in `seed-art/pieces.ts`, rendered with sharp). Nothing was',
    'downloaded, traced or copied from existing works, and nothing was generated by an AI image service.',
    '',
    'They are part of this repository and licensed with it under the MIT License (see `LICENSE` in the repository root).',
    '',
    'Generated by `pnpm --filter @app/api seed:generate-art`. Do not edit by hand.',
    '',
    ...list,
    '',
  ].join('\n');
}

/**
 * Checks that artwork, content and manifest name the same slugs in the same order before anything is written, then
 * renders every piece in memory. Every file goes to `<name>.tmp` first and is renamed into place only after all of
 * them were written, so a failed run leaves the committed set as it was (at worst a few `.tmp` files).
 */
export async function generateSeedArt({ dir = SEED_IMAGES_DIR } = {}): Promise<void> {
  const entries = joinSeed(await readManifest(dir));
  const contentOrder = entries.map((entry) => entry.image.slug).join(',');
  const artOrder = SEED_ARTWORKS.map((artwork) => artwork.slug).join(',');
  if (contentOrder !== artOrder)
    throw new Error(`Seed artwork and content disagree:\n  art: ${artOrder}\n  content: ${contentOrder}`);

  const rendered = await Promise.all(
    SEED_ARTWORKS.map(async (artwork) => ({ artwork, jpeg: await renderJpeg(artwork) })),
  );
  const files: [string, Buffer | string][] = [
    ...rendered.map(({ artwork, jpeg }): [string, Buffer] => [`${artwork.slug}.jpg`, jpeg]),
    ['CREDITS.md', renderCredits()],
  ];
  for (const [name, content] of files) await writeFile(join(dir, `${name}.tmp`), content);
  for (const [name, content] of files) {
    await rename(join(dir, `${name}.tmp`), join(dir, name));
    process.stdout.write(`wrote ${name} (${String(Math.round(content.length / 1024))} KB)\n`);
  }
}

if (import.meta.main) {
  await runCli('seed:generate-art', async () => {
    const args = cliArgs(process.argv.slice(2));
    if (args.length > 0) throw new Error(`unknown argument(s) ${args.join(' ')}. Usage: no arguments`);
    await generateSeedArt();
    return 0;
  });
}
