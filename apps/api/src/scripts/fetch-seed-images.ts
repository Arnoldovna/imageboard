/**
 * `pnpm --filter @app/api seed:fetch-images [--force]`: one-off download of the seed photographs (ADR 0014,
 * DATA-MODEL §6.2). For every entry of `seed/images/manifest.json` it asks Lorem Picsum for the photo's author and
 * Unsplash URL, downloads the photo, writes `seed/images/<slug>.jpg` (long edge ≤ 1600 px, JPEG q80, no metadata),
 * fills `author`, `sourceUrl` and `fetchedAt` back into the manifest and regenerates `CREDITS.md`.
 *
 * The output is committed, so `db:seed` works offline and nothing points at a third party at runtime (B-44). Photos
 * that are already present with complete credits are kept unless `--force` is given; `CREDITS.md` is always rewritten.
 */
import { access, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import sharp from 'sharp';
import { z } from 'zod';

import {
  MANIFEST_FILE,
  readManifest,
  SEED_IMAGES,
  SEED_IMAGES_DIR,
  SEED_LICENCE,
  type SeedImage,
  SeedManifest,
  SeedManifestDraft,
  type SeedManifestDraftEntry,
  type SeedManifestEntry,
} from './seed-content.js';
import { cliArgs, runCli } from './script-runtime.js';

/** Long edge of a stored seed photo; the upload pipeline keeps it (IMAGE_MAX_EDGE is larger). */
export const SEED_MAX_EDGE = 1600;
const JPEG_QUALITY = 80;
const REQUEST_TIMEOUT_MS = 60_000;
const PICSUM = 'https://picsum.photos';
const LICENCE_URL = 'https://unsplash.com/license';

/** `GET https://picsum.photos/id/<id>/info`: `url` is the photo's Unsplash page, `download_url` the full image. */
const PicsumInfo = z.object({
  id: z.string(),
  // Picsum has names with doubled spaces ("Yamon  Figurs"); credits show them as people write them.
  author: z
    .string()
    .transform((name) => name.replace(/\s+/g, ' ').trim())
    .pipe(z.string().min(1)),
  url: z.url({ protocol: /^https$/ }),
  download_url: z.url({ protocol: /^https$/ }),
});

async function fetchOk(url: string): Promise<Response> {
  const response = await fetch(url, { signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS), redirect: 'follow' });
  if (!response.ok) throw new Error(`GET ${url} answered ${String(response.status)}`);
  return response;
}

/** Resized inside a 1600 px square, auto-oriented, re-encoded; sharp drops EXIF/XMP/IPTC unless asked to keep them. */
export async function toSeedJpeg(bytes: Uint8Array): Promise<Buffer> {
  return sharp(bytes)
    .rotate()
    .resize({ width: SEED_MAX_EDGE, height: SEED_MAX_EDGE, fit: 'inside', withoutEnlargement: true })
    .jpeg({ quality: JPEG_QUALITY, mozjpeg: true })
    .toBuffer();
}

async function exists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

function isComplete(entry: SeedManifestDraftEntry): boolean {
  return entry.author !== undefined && entry.sourceUrl !== undefined && entry.fetchedAt !== undefined;
}

/** Downloads and converts one photo in memory; the caller writes it once every entry has succeeded. */
async function fetchEntry(
  entry: SeedManifestDraftEntry,
  today: string,
): Promise<{ entry: SeedManifestEntry; jpeg: Buffer }> {
  const info = PicsumInfo.parse(await (await fetchOk(`${PICSUM}/id/${String(entry.picsumId)}/info`)).json());
  const original = new Uint8Array(await (await fetchOk(info.download_url)).arrayBuffer());
  return {
    entry: { ...entry, author: info.author, sourceUrl: info.url, licence: SEED_LICENCE, fetchedAt: today },
    jpeg: await toSeedJpeg(original),
  };
}

/** Markdown that Prettier leaves as it is (no tables to re-align), so a re-run never fails `format:check`. */
export function renderCredits(entries: readonly SeedManifestEntry[], images: readonly SeedImage[] = SEED_IMAGES) {
  const titles = new Map(images.map((image) => [image.slug, image.title]));
  const sections = entries.map((entry) =>
    [
      `## ${entry.slug}.jpg`,
      '',
      `- Title in the seed: ${titles.get(entry.slug) ?? entry.slug}`,
      `- Photographer: ${entry.author}`,
      `- Source: <${entry.sourceUrl}>`,
      `- Lorem Picsum id: ${String(entry.picsumId)}`,
      `- Licence: [${entry.licence}](${LICENCE_URL})`,
      `- Fetched: ${entry.fetchedAt}`,
    ].join('\n'),
  );
  return [
    '# Seed image credits',
    '',
    'The demo content of `pnpm db:seed` uses these photographs. They were downloaded once through',
    '[Lorem Picsum](https://picsum.photos), which serves photographs from Unsplash, resized to at most',
    `${String(SEED_MAX_EDGE)} px and re-encoded without metadata. Every photo is under the`,
    `[Unsplash License](${LICENCE_URL}), which does not require attribution; the photographers are credited anyway.`,
    '',
    'Generated by `pnpm --filter @app/api seed:fetch-images` from `manifest.json`. Do not edit by hand.',
    '',
    ...sections.flatMap((section) => [section, '']),
  ].join('\n');
}

/**
 * Nothing is written until every entry has been downloaded and the complete manifest validates, so a network error
 * part-way never leaves new photos next to the old photographers' credits (or the reverse). `fetchedAt` is the UTC
 * date of the run.
 */
export async function fetchSeedImages({ dir = SEED_IMAGES_DIR, force = false } = {}): Promise<void> {
  const draft = await readManifest(dir, SeedManifestDraft);
  const today = new Date().toISOString().slice(0, 10);
  const updated: SeedManifestDraftEntry[] = [];
  const photos = new Map<string, Buffer>();
  for (const entry of draft) {
    if (!force && isComplete(entry) && (await exists(join(dir, `${entry.slug}.jpg`)))) {
      process.stdout.write(`kept    ${entry.slug}.jpg\n`);
      updated.push(entry);
      continue;
    }
    const fetched = await fetchEntry(entry, today);
    updated.push(fetched.entry);
    photos.set(entry.slug, fetched.jpeg);
    process.stdout.write(`fetched ${entry.slug}.jpg (Picsum ${String(entry.picsumId)})\n`);
  }
  // Every entry is complete now; the strict schema proves it before anything is written.
  const manifest = SeedManifest.parse(updated);
  for (const [slug, jpeg] of photos) await writeFile(join(dir, `${slug}.jpg`), jpeg);
  await writeFile(join(dir, MANIFEST_FILE), `${JSON.stringify(manifest, null, 2)}\n`);
  await writeFile(join(dir, 'CREDITS.md'), renderCredits(manifest));
}

if (import.meta.main) {
  await runCli('seed:fetch-images', async () => {
    const args = cliArgs(process.argv.slice(2));
    const unknown = args.filter((arg) => arg !== '--force');
    if (unknown.length > 0) throw new Error(`unknown argument(s) ${unknown.join(' ')}. Usage: [--force]`);
    await fetchSeedImages({ force: args.includes('--force') });
    return 0;
  });
}
